/**
 * 화면 표시 전용 한글 줄바꿈 보정.
 * "주소·카드"처럼 가운뎃점으로 묶인 말이 줄 끝에서 갈라져 다음 줄이 "·카드"로 시작하지 않도록
 * 가운뎃점 앞에 보이지 않는 단어 결합 문자(U+2060)를 넣는다. 가운뎃점 뒤에서는 줄이 바뀔 수 있어
 * "인증번호·비밀번호·카드번호"처럼 긴 묶음도 좁은 화면에서 넘치지 않는다. CSS(word-break·line-break)로는 막을 수 없다.
 * 저장·공유되는 문구에는 쓰지 않는다.
 */
export const keepDots = (text: string): string => text.replace(/·/g, "\u2060·");
